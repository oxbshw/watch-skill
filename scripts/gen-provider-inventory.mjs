#!/usr/bin/env node
/**
 * The provider catalogue the pinned DSH actually ships.
 *
 * Read from source, never from memory. The question this answers is narrow and
 * load-bearing: **has Watch narrowed the provider choice?** Watch is a layer on
 * DSH, and a layer that quietly reduced a person's options from the full
 * catalogue to whichever provider the layer's author happened to use would be a
 * regression no test elsewhere would notice.
 *
 * The catalogue lives in `@earendil-works/pi-ai`, vendored under
 * `@deepseek-ai/dsh-llm-pi-ai`, and each provider declares its own id, display
 * name, base URL, auth method and wire protocol. That declaration is what is
 * recorded here.
 *
 * What the inventory deliberately does *not* record is whether a provider
 * works. A descriptor existing means the route is shipped and reachable; it
 * says nothing about whether anyone has a credential for it or whether it has
 * ever answered. Every row therefore carries `checked: "never"` until a real
 * connection test has run, because "available" and "present in the catalogue"
 * are exactly the two things this product refuses to conflate.
 *
 * Usage:
 *   node scripts/gen-provider-inventory.mjs           write the inventory
 *   node scripts/gen-provider-inventory.mjs --check   fail if it is stale
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'inventory', 'dsh-providers.json')

/**
 * The summary the product renders.
 *
 * Emitted as a module rather than read at runtime so the Technology Center
 * cannot drift from the catalogue: the number on screen is generated from the
 * same walk that produced the inventory, and `--check` fails if either is
 * stale. Hardcoding "37 providers" in a component is how a UI ends up
 * confidently stating last quarter's catalogue.
 */
const MODULE = join(ROOT, 'packages', 'watch', 'client-settings', 'src', 'providers.ts')

function moduleSource(document) {
  const ids = document.providers.map(provider => provider.id)
  return [
    '/**',
    ' * What the pinned DSH provider catalogue contains.',
    ' *',
    ' * Generated by `scripts/gen-provider-inventory.mjs` from',
    ' * `@earendil-works/pi-ai`. Do not edit: the catalogue is the source of',
    ' * truth and this is a count of it.',
    ' *',
    ' * @module @watchskill/dsh-client-settings/providers',
    ' */',
    '',
    '/** Every provider route the pinned DSH ships. */',
    `export const PROVIDER_COUNT = ${String(document.total)}`,
    '',
    '/** Routes you reach over a network somebody else runs. */',
    `export const HOSTED_COUNT = ${String(document.counts.hosted ?? 0)}`,
    '',
    '/**',
    ' * Routes where you supply the endpoint.',
    ' *',
    ' * This is the same mechanism a local model uses: an OpenAI-compatible',
    ' * server on your own machine — Ollama, vLLM, LM Studio, llama.cpp — is a',
    ' * base URL you provide, not a separate feature.',
    ' */',
    `export const SELF_HOSTED_COUNT = ${String(document.counts.self_hosted ?? 0)}`,
    '',
    '/** Whether DeepSeek is one route among many rather than the only one. */',
    `export const DEEPSEEK_IS_OPTIONAL = ${String(ids.includes('deepseek') && document.total > 1)}`,
    '',
    '/** A few recognisable names, for a sentence that has to stay short. */',
    `export const SAMPLE_PROVIDERS = ${JSON.stringify(
      ids.filter(id => ['openai', 'anthropic', 'google', 'mistral', 'groq', 'deepseek', 'amazon-bedrock', 'openrouter'].includes(id)),
    )}`,
    '',
  ].join('\n')
}

const TREES = [
  process.env.WATCH_DSH_TREE,
  'G:/watch-smoke/node_modules',
  'G:/watch-manual/dsh-home/profiles/web/node_modules',
  join(ROOT, 'node_modules'),
].filter(path => path !== undefined)

/** Find pi-ai's provider directory under whichever tree has a DSH install. */
function providerDirectory() {
  for (const tree of TREES) {
    const store = join(tree, '.pnpm')
    if (!existsSync(store)) continue
    for (const entry of readdirSync(store)) {
      const candidate = join(
        store, entry, 'node_modules', '@earendil-works', 'pi-ai', 'dist', 'providers',
      )
      if (existsSync(candidate)) return candidate
    }
  }
  return null
}

/**
 * Classify a route by how a person reaches it.
 *
 * `hosted` is somebody else's endpoint over the network. `self_hosted` is an
 * endpoint you run — the OpenAI-compatible route is how a local server (Ollama,
 * vLLM, LM Studio, llama.cpp) is reached, which is why "local model" and
 * "custom provider" are the same mechanism here rather than two features.
 * `test` is a fixture route that talks to nothing.
 */
function classify(id, baseUrl) {
  if (id === 'faux') return 'test'
  if (baseUrl === null || baseUrl === '') return 'self_hosted'
  if (/localhost|127\.0\.0\.1/.test(baseUrl)) return 'self_hosted'
  return 'hosted'
}

function main() {
  const check = process.argv.includes('--check')
  const directory = providerDirectory()
  if (directory === null) {
    if (check && existsSync(OUT)) {
      process.stdout.write('providers: no DSH tree here; keeping the committed inventory\n')
      return
    }
    process.stderr.write('watch: no pi-ai provider catalogue found. Set WATCH_DSH_TREE.\n')
    process.exit(1)
  }

  // `all.js` is the shipped set. A provider file that nothing imports is not in
  // the catalogue, so the import list is the authority rather than the folder.
  const all = readFileSync(join(directory, 'all.js'), 'utf8')
  const shipped = [...all.matchAll(/from "\.\/([a-z0-9.-]+)\.js"/g)]
    .map(match => match[1])
    .filter(name => !name.endsWith('.models') && !['all', 'data/.manifest'].includes(name))

  const providers = []
  const seen = new Set()
  for (const file of [...new Set(shipped)].sort()) {
    const path = join(directory, `${file}.js`)
    if (!existsSync(path)) continue
    const source = readFileSync(path, 'utf8')

    // Anchored to the `createProvider({...})` call, not to the first `id:` in
    // the file. Several providers declare an auth method above it — Bedrock's
    // `bearer-token`, Vertex's `api-key` — and an unanchored match records the
    // credential kind as the provider name.
    const call = /createProvider\(\{[\s\S]*?\n\s*\}\)/.exec(source)?.[0] ?? source
    const id = /\bid:\s*"([^"]+)"/.exec(call)?.[1]
    if (id === undefined) continue
    const name = /\bname:\s*"([^"]+)"/.exec(call)?.[1] ?? id
    const baseUrl = /\bbaseUrl:\s*"([^"]+)"/.exec(call)?.[1] ?? null
    const api = /(\w+)Api\(\)/.exec(source)?.[1] ?? null
    const envKeys = [...source.matchAll(/\[\s*"([A-Z0-9_]+)"/g)].map(match => match[1])

    // One file can ship two routes (openrouter and openrouter-images). The id
    // is the key, so a second file naming the same id is not a second row.
    if (seen.has(id)) continue
    seen.add(id)

    providers.push({
      id,
      name,
      classification: classify(id, baseUrl),
      protocol: api,
      baseUrl,
      // The name of the variable DSH reads, never a value. No secret is
      // recorded here, and none can be: this is a schema, not a store.
      credentialEnv: [...new Set(envKeys)],
      configuredVia: 'DSH Settings → Models & Providers',
      reachableFromUi: true,
      requiresPlugin: false,
      // A descriptor existing is not a working connection. Nothing here has
      // been contacted, so nothing here claims to work.
      checked: 'never',
      state: 'shipped in the pinned catalogue; not configured and not contacted',
    })
  }

  if (providers.length === 0) {
    process.stderr.write(`watch: found ${directory} but no provider descriptors\n`)
    process.exit(1)
  }

  const counts = {}
  for (const provider of providers) {
    counts[provider.classification] = (counts[provider.classification] ?? 0) + 1
  }

  const document = {
    generatedBy: 'scripts/gen-provider-inventory.mjs',
    source: '@earendil-works/pi-ai, vendored by @deepseek-ai/dsh-llm-pi-ai',
    note:
      'Every provider route the pinned DSH ships. Watch narrows none of them: '
      + 'it adds no provider, removes none, and stores no credential — bindings '
      + 'reference a credential DSH holds. `checked: "never"` on every row is '
      + 'literal: a descriptor existing means the route is shipped, not that it '
      + 'works, and this product does not conflate the two. Only variable NAMES '
      + 'are recorded, never values.',
    deepseekIsOptional: true,
    counts,
    total: providers.length,
    providers,
  }

  const json = `${JSON.stringify(document, null, 2)}\n`

  if (check) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== json) {
      process.stderr.write('watch: inventory/dsh-providers.json is stale — run `node scripts/gen-provider-inventory.mjs`\n')
      process.exit(1)
    }
    process.stdout.write(`providers: current — ${String(providers.length)} route(s)\n`)
    return
  }

  writeFileSync(OUT, json, 'utf8')
  writeFileSync(MODULE, moduleSource(document), 'utf8')
  process.stdout.write(
    `providers: ${String(providers.length)} route(s) in the pinned catalogue\n`
    + Object.entries(counts).sort()
      .map(([kind, count]) => `  ${kind.padEnd(12)} ${String(count)}\n`).join(''),
  )
}

main()
