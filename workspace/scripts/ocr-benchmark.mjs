#!/usr/bin/env node
/**
 * Score a real OCR run against thresholds that were set before it.
 *
 * The measuring is done by the product's own functions — `characterErrorRate`,
 * `wordErrorRate`, `wordAccuracy`, `hallucinationRate`, `omissionRate` — and
 * judged against `DEFAULT_THRESHOLDS`, which were written and committed long
 * before this benchmark existed. That ordering is the point. Choosing a
 * threshold after seeing a number is not a threshold, it is a description.
 *
 * The raw run comes from `ocr-corpus.py`, which drives the actual engine on
 * actual images. This never invents a measurement and never runs an engine
 * itself: if the run is missing, it says so and reports nothing.
 *
 * Latency is recorded and reported but deliberately not gated. Speed on one
 * unloaded laptop is not a release criterion, and a threshold on it would fail
 * for reasons that have nothing to do with whether the text was read correctly.
 *
 * Usage:
 *   node scripts/ocr-benchmark.mjs [--raw <dir>] [--check]
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  DEFAULT_THRESHOLDS, characterErrorRate, hallucinationRate, omissionRate,
  wordAccuracy, wordErrorRate,
} from '@watchskill/dsh-technology/descriptors'

import { manualPath } from './lib/manual-paths.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const RAW = manualPath('WATCH_OCR_DIR', ['ocr'])
const OUT = join(ROOT, 'docs', 'ocr-benchmark.json')

/**
 * The measured numbers, as a module the product can render.
 *
 * The Technology Center said "Not measured on this machine" for every engine.
 * That was true and is no longer, and a surface whose honesty depends on
 * nobody having run the benchmark is not honest — it is merely unfalsified.
 * Emitting the result means the screen changes when the measurement does.
 */
const MODULE = join(ROOT, 'packages', 'watch', 'client-settings', 'src', 'ocr-measured.ts')

function moduleSource(document) {
  const rows = document.measured === true
    ? Object.entries(document.byWorkload).sort().map(([workload, set]) => ({
      workload,
      samples: set.samples,
      cer: set.cer,
      wordAccuracy: set.wordAccuracy,
      hallucination: set.hallucination,
      passes: set.passesThresholds,
    }))
    : []
  return [
    '/**',
    ' * What OCR actually measured on this machine.',
    ' *',
    ' * Generated by `scripts/ocr-benchmark.mjs` from a real run over a versioned',
    ' * ground-truth corpus. Do not edit: a number typed into a component is a',
    ' * number nobody measured.',
    ' *',
    ' * @module @watchskill/dsh-client-settings/ocr-measured',
    ' */',
    '',
    '/** One workload tier, with the numbers the run produced. */',
    'export interface MeasuredWorkload {',
    '  readonly workload: string',
    '  readonly samples: number',
    '  readonly cer: number',
    '  readonly wordAccuracy: number',
    '  readonly hallucination: number',
    '  /** Against thresholds committed before the benchmark existed. */',
    '  readonly passes: boolean',
    '}',
    '',
    '/** Whether any engine has been measured here at all. */',
    `export const OCR_MEASURED = ${String(document.measured === true)}`,
    '',
    '/** The engine that was run, and where. */',
    `export const OCR_ENGINE = ${JSON.stringify(document.engine ?? 'none')}`,
    `export const OCR_DEVICE = ${JSON.stringify(document.device ?? 'none')}`,
    '',
    '/** Per workload, because qualification is per workload and not an average. */',
    `export const OCR_BY_WORKLOAD: readonly MeasuredWorkload[] = ${JSON.stringify(rows, null, 2)}`,
    '',
  ].join(String.fromCharCode(10))
}

/**
 * Which workload each sample belongs to.
 *
 * `qualify()` is defined per engine x workload x script, so reporting one
 * average across a corpus that deliberately mixes clean UI text with
 * adversarial samples would answer a question nobody asked: an engine can be
 * entirely fit for reading a settings panel and entirely unfit for reading
 * grey-on-grey at 24px, and a single number hides both facts.
 *
 * The mapping is fixed here, before the run is read, for the same reason the
 * thresholds are: a tier chosen after seeing a result is not a tier.
 */
const WORKLOADS = {
  'clean-ui-en': 'ui_text',
  'clean-ui-dark': 'dark_mode',
  'small-text': 'ui_text',
  'tiny-text': 'low_resolution',
  'low-contrast': 'low_resolution',
  'very-low-contrast': 'low_resolution',
  'error-code': 'ui_text',
  timestamp: 'video_overlay',
  identifier: 'ui_text',
  digest: 'ui_text',
  'mixed-case': 'ui_text',
  'tracked-out': 'low_resolution',
  'long-line': 'document',
  numbers: 'ui_text',
  punctuation: 'ui_text',
  arabic: 'mixed_script',
  'arabic-mixed': 'mixed_script',
  blank: 'ui_text',
}

const mean = values => (values.length === 0 ? 0 : values.reduce((a, b) => a + b, 0) / values.length)

function main() {
  const check = process.argv.includes('--check')
  const rawPath = join(RAW, 'raw-results.json')

  if (!existsSync(rawPath)) {
    if (check && existsSync(OUT)) {
      process.stdout.write('ocr: no run present; keeping the committed benchmark\n')
      return
    }
    process.stderr.write(
      `watch: no OCR run at ${rawPath}.\n`
      + '       Run: python scripts/ocr-corpus.py --out <dir>\n',
    )
    process.exit(1)
  }

  const raw = JSON.parse(readFileSync(rawPath, 'utf8'))
  if (raw.available !== true) {
    // An absent engine is a fact to report, not a reason to fabricate one.
    const document = {
      generatedBy: 'scripts/ocr-benchmark.mjs',
      engine: raw.engine,
      measured: false,
      reason: raw.reason ?? 'the engine could not be loaded',
      note:
        'No accuracy is claimed. An engine that could not be loaded has not been '
        + 'measured, and an unmeasured engine has no error rate.',
    }
    writeFileSync(OUT, `${JSON.stringify(document, null, 2)}\n`, 'utf8')
    process.stdout.write(`ocr: engine unavailable — ${String(document.reason)}\n`)
    return
  }

  // `hallucinationRate` and `omissionRate` compare *regions*. The granularity
  // is a real methodological choice, and the obvious one is wrong: at one
  // region per line, any single wrong character makes the whole line "not
  // expected", so both metrics collapse into exact-match and stop measuring
  // what they are named for.
  //
  // A word is the right unit here. Hallucination then means "returned a word
  // that is not in the source" — inventing — and omission means "did not
  // return a word that is" — missing. Those are the two failures that matter,
  // and they are genuinely different: an engine that omits is safe and
  // unhelpful, one that invents is dangerous.
  const asRegions = text => text.trim().split(/\s+/)
    .filter(word => word !== '')
    .map((word, order) => ({ text: word, bbox: { x: order, y: 0, width: 1, height: 1 }, order }))

  const samples = raw.results.map(result => {
    const negative = result.negative === true
    const expectedRegions = asRegions(result.expected)
    const actualRegions = asRegions(result.actual)
    return {
      id: result.id,
      workload: WORKLOADS[result.id] ?? 'ui_text',
      script: result.script,
      negative,
      crashed: result.crashed === true,
      expected: result.expected,
      actual: result.actual,
      ms: result.ms,
      // A negative sample has no text, so an error *rate* over zero characters
      // is meaningless. What matters there is whether the engine invented
      // something, which hallucination measures directly.
      cer: negative ? null : characterErrorRate(result.expected, result.actual),
      wer: negative ? null : wordErrorRate(result.expected, result.actual),
      wordAccuracy: negative ? null : wordAccuracy(result.expected, result.actual),
      hallucination: hallucinationRate(expectedRegions, actualRegions),
      omission: negative ? null : omissionRate(expectedRegions, actualRegions),
      exact: result.expected.trim() === result.actual.trim(),
    }
  })

  const scored = samples.filter(sample => !sample.negative && !sample.crashed)
  const latin = scored.filter(sample => sample.script === 'latin')
  const other = scored.filter(sample => sample.script !== 'latin')

  const summarise = set => ({
    samples: set.length,
    cer: Number(mean(set.map(s => s.cer)).toFixed(4)),
    wer: Number(mean(set.map(s => s.wer)).toFixed(4)),
    wordAccuracy: Number(mean(set.map(s => s.wordAccuracy)).toFixed(4)),
    hallucination: Number(mean(set.map(s => s.hallucination)).toFixed(4)),
    omission: Number(mean(set.map(s => s.omission)).toFixed(4)),
    exactFieldAccuracy: Number((set.filter(s => s.exact).length / Math.max(1, set.length)).toFixed(4)),
    meanLatencyMs: Number(mean(set.map(s => s.ms)).toFixed(1)),
    p95LatencyMs: Number(
      [...set.map(s => s.ms)].sort((a, b) => a - b)[Math.floor(set.length * 0.95)] ?? 0,
    ),
  })

  const overall = summarise(scored)

  // Per workload, which is the unit the qualification model actually uses.
  const byWorkload = {}
  for (const workload of new Set(scored.map(sample => sample.workload))) {
    const set = scored.filter(sample => sample.workload === workload)
    byWorkload[workload] = {
      ...summarise(set),
      passesThresholds:
        summarise(set).cer <= DEFAULT_THRESHOLDS.maxCer
        && summarise(set).wordAccuracy >= DEFAULT_THRESHOLDS.minWordAccuracy
        && summarise(set).hallucination <= DEFAULT_THRESHOLDS.maxHallucinationRate
        && summarise(set).omission <= DEFAULT_THRESHOLDS.maxOmissionRate,
    }
  }
  const negatives = samples.filter(sample => sample.negative)

  // Judged against thresholds that predate this benchmark. Latin is the tier
  // the engine's shipped models are trained for; other scripts are measured
  // and reported separately rather than averaged into a number that would hide
  // both.
  const latinSummary = summarise(latin)
  const verdicts = {
    cer: { value: latinSummary.cer, threshold: DEFAULT_THRESHOLDS.maxCer, pass: latinSummary.cer <= DEFAULT_THRESHOLDS.maxCer },
    wordAccuracy: {
      value: latinSummary.wordAccuracy,
      threshold: DEFAULT_THRESHOLDS.minWordAccuracy,
      pass: latinSummary.wordAccuracy >= DEFAULT_THRESHOLDS.minWordAccuracy,
    },
    hallucination: {
      value: latinSummary.hallucination,
      threshold: DEFAULT_THRESHOLDS.maxHallucinationRate,
      pass: latinSummary.hallucination <= DEFAULT_THRESHOLDS.maxHallucinationRate,
    },
    omission: {
      value: latinSummary.omission,
      threshold: DEFAULT_THRESHOLDS.maxOmissionRate,
      pass: latinSummary.omission <= DEFAULT_THRESHOLDS.maxOmissionRate,
    },
  }

  const document = {
    generatedBy: 'scripts/ocr-benchmark.mjs',
    engine: raw.engine,
    device: raw.device,
    corpusVersion: raw.corpusVersion,
    measured: true,
    thresholds: DEFAULT_THRESHOLDS,
    thresholdsSetBefore: 'packages/watch/technology/src/ocr-qualification.ts, committed before this benchmark existed',
    overall,
    byScript: { latin: latinSummary, other: summarise(other) },
    byWorkload,
    negatives: negatives.map(sample => ({
      id: sample.id,
      returned: sample.actual,
      hallucinated: sample.actual.trim() !== '',
    })),
    verdicts,
    crashRate: Number((samples.filter(s => s.crashed).length / Math.max(1, samples.length)).toFixed(4)),
    samples,
    note:
      'CPU only; no GPU is present on this machine, so GPU throughput remains '
      + 'externally unvalidated. Accuracy is not a GPU question and is measured '
      + 'here. Latency is reported but not gated: speed on one unloaded machine '
      + 'is not a release criterion.',
  }

  const json = `${JSON.stringify(document, null, 2)}\n`
  if (check) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== json) {
      process.stderr.write('watch: docs/ocr-benchmark.json is stale — re-run the benchmark\n')
      process.exit(1)
    }
    process.stdout.write('ocr: benchmark current\n')
    return
  }

  writeFileSync(OUT, json, 'utf8')
  writeFileSync(MODULE, moduleSource(document), 'utf8')
  process.stdout.write(
    `ocr: ${raw.engine} on ${raw.device}, corpus v${String(raw.corpusVersion)}\n`
    + `  scored          ${String(scored.length)} sample(s)  (latin ${String(latin.length)}, other ${String(other.length)})\n`
    + Object.entries(verdicts).map(([name, verdict]) =>
      `  ${name.padEnd(15)} ${String(verdict.value).padEnd(8)} vs ${String(verdict.threshold).padEnd(6)} ${verdict.pass ? 'pass' : 'FAIL'}\n`).join('')
    + `  exact fields    ${String(latinSummary.exactFieldAccuracy)}\n`
    + `  mean latency    ${String(overall.meanLatencyMs)}ms  p95 ${String(overall.p95LatencyMs)}ms\n`
    + `  crash rate      ${String(document.crashRate)}\n`,
  )
}

main()
